
#converting decimal number into binary format
# Using bin() function
decimal_number = 10
binary_representation = bin(decimal_number)
print(f"Binary representation of {decimal_number} is {binary_representation}")


#converting decimal number into octal format
# Using oct() function
octal_representation = oct(decimal_number)
print(f"Octal representation of {decimal_number} is {octal_representation}")

#converting decimal number into hexadecimal format
# Using hex() function
hexadecimal_representation = hex(decimal_number)
print(f"Hexadecimal representation of {decimal_number} is {hexadecimal_representation}")


#converting binary number into decimal format
# Using int() function with base 2
binary_number = '1010'
decimal_representation = int(binary_number, 2)
print(f"Decimal representation of binary {binary_number} is {decimal_representation}")





